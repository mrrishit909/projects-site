-- ProductSignal reference metrics: an independent recomputation, in SQL, of every metric key of expected.json
-- (signup_conversion, funnel, activation, retention, feature_adoption, experiment) plus tracking_quality and identity.
--
-- Independent of the Python domain: it reads only facts (events with their received_at, identity links, accounts, users,
-- sessions, subscriptions, assignments, exposures, observations, analysis runs, the stored plan and metric windows, the funnel
-- definition) and no stored status, result or derived column. One statement, one row, one jsonb column per metric.
--
-- Parameters (psycopg): %(cutoff)s timestamptz; %(xv)s experiment version id or NULL (the plan frozen last); %(run_id)s analysis
-- id or NULL (the run whose cutoff_at equals the cutoff).
--
-- Exactness: counts are integers; ratios, Wilson and Newcombe bounds are NUMERIC (square roots at 40 decimals), rounded once by
-- round() (half away from zero = ROUND_HALF_UP on the values published here). The chi-square p-value is computed here too:
-- erfc(sqrt(stat/2)) = 1 - erf(x) by the Maclaurin series of erf in NUMERIC at 90 decimals, terms until |term| <= 1e-70 (the
-- same stopping rule as the Python reference), with pi as a 100-decimal literal. The Student t quantile cannot be reproduced
-- here (a bisection on the t CDF): the quantile of each variant's df is read from t_critical_975, a table generated by
-- Python at 20 decimals (data/sql/generate_t_quantiles.py); the standard error, the mean and the interval bounds are SQL.
-- The table is only valid for the 95 percent interval; another plan confidence gives a NULL interval here.
WITH RECURSIVE
p AS (SELECT %(cutoff)s::timestamptz AS cutoff),
cfg AS (SELECT windows AS j FROM metric_config WHERE id = 1),
w AS (
    SELECT (j->'signup_conversion'->>'from')::timestamptz AS sc_from, (j->'signup_conversion'->>'to')::timestamptz AS sc_to,
           (j->'activation'->>'from')::timestamptz AS ac_from, (j->'activation'->>'to')::timestamptz AS ac_to,
           (j->'activation'->>'window_days')::int AS ac_days,
           (j->'retention'->>'signup_from')::date AS rt_from, (j->'retention'->>'signup_to')::date AS rt_to,
           (j->'feature_adoption'->>'from')::timestamptz AS fa_from, (j->'feature_adoption'->>'to')::timestamptz AS fa_to,
           j->'feature_adoption'->>'feature' AS fa_feature, j->'feature_adoption'->'eligible_plans' AS fa_plans
    FROM cfg
),
fd AS (
    SELECT * FROM funnel_definitions ORDER BY created_at DESC, definition_id DESC, version DESC LIMIT 1
),
pl AS (
    SELECT experiment_version_id AS xv, plan AS j, config_hash, plan->>'primary_metric' AS primary_metric,
           plan->>'unit_type' AS unit_type, plan->'allocation' AS alloc, (plan->>'planned_end')::timestamptz AS planned_end,
           (plan->>'activation_window_days')::int AS win, (plan->'guardrail'->>'window_days')::int AS g_days,
           plan->'guardrail'->>'metric' AS g_metric, (plan->'revenue_window'->>'from')::timestamptz AS rev_from,
           (plan->'revenue_window'->>'to')::timestamptz AS rev_to, plan->>'confidence' AS confidence, (plan->>'z')::numeric AS z,
           plan->>'z' AS z_text, (plan->'srm'->>'p_threshold')::numeric AS p_threshold,
           (plan->'srm'->>'min_expected_cell')::numeric AS min_cell, (plan->>'frozen_at')::timestamptz AS frozen_at,
           encode(sha256(convert_to(ps_canonical_json(plan), 'UTF8')), 'hex') = config_hash AS hash_ok
    FROM analysis_plans
    WHERE %(xv)s::text IS NULL OR experiment_version_id = %(xv)s::text
    ORDER BY (plan->>'frozen_at')::timestamptz DESC, experiment_version_id DESC LIMIT 1
),

-- ---- canonical events (D-01, D-05): received by the cutoff, deduplicated, identity in time, exclusions -------------------
first_link AS (
    SELECT DISTINCT ON (anonymous_id) anonymous_id, user_id, linked_at FROM identity_links
    ORDER BY anonymous_id, linked_at, identity_link_id
),
anon_of_user AS (
    SELECT DISTINCT ON (user_id) user_id, anonymous_id FROM identity_links ORDER BY user_id, linked_at, identity_link_id
),
recv AS (
    SELECT e.*, coalesce(e.user_id, e.anonymous_id) AS actor,
           coalesce((SELECT jsonb_object_agg(ep.property_key, ep.property_value) FROM event_properties ep
                     WHERE ep.event_id = e.event_id), '{}'::jsonb) AS props
    FROM events e, p WHERE e.received_at <= p.cutoff
),
ranked AS (
    SELECT recv.*, row_number() OVER (PARTITION BY actor, event_name, event_at, props ORDER BY received_at, event_id) AS rn FROM recv
),
canon AS (SELECT * FROM ranked WHERE rn = 1),
resolved AS (
    SELECT c.*, CASE WHEN c.user_id IS NOT NULL THEN c.user_id WHEN fl.linked_at <= c.event_at THEN fl.user_id END AS u
    FROM canon c LEFT JOIN first_link fl ON fl.anonymous_id = c.anonymous_id
),
classified AS (
    SELECT r.*, u2.account_id AS acct,
           CASE WHEN (r.user_id IS NULL AND r.anonymous_id IS NULL) OR (r.u IS NOT NULL AND u2.user_id IS NULL) THEN 'unknown'
                WHEN r.u IS NOT NULL AND u2.bot_flag THEN 'bot'
                WHEN r.u IS NOT NULL AND a2.internal THEN 'internal'
                ELSE 'analysed' END AS cls
    FROM resolved r LEFT JOIN users u2 ON u2.user_id = r.u LEFT JOIN accounts a2 ON a2.account_id = u2.account_id
),
ev AS (
    SELECT c.event_id, c.user_id, c.anonymous_id, c.event_name AS name, c.event_at AS at, c.u, c.acct,
           coalesce(c.anonymous_id, (SELECT anonymous_id FROM anon_of_user WHERE user_id = c.user_id), 'user:' || c.user_id) AS vk,
           c.props
    FROM classified c WHERE c.cls = 'analysed'
),
tq AS (
    SELECT (SELECT count(*) FROM events) AS rows_total,
           (SELECT count(*) FROM events, p WHERE received_at > p.cutoff) AS received_after_cutoff,
           (SELECT count(*) FROM recv) - (SELECT count(*) FROM canon) AS duplicates_dropped,
           (SELECT count(*) FROM canon) AS canonical,
           (SELECT count(*) FROM canon WHERE received_at - event_at > interval '24 hours') AS delayed_over_24h,
           (SELECT count(*) FROM classified WHERE cls = 'unknown') AS unknown_identity,
           (SELECT count(*) FROM classified WHERE cls = 'bot') AS bot_events_excluded,
           (SELECT count(*) FROM classified WHERE cls = 'internal') AS internal_events_excluded,
           (SELECT count(*) FROM ev) AS analysed
),
idn AS (
    SELECT count(*) AS anonymous_events, count(*) FILTER (WHERE u IS NOT NULL) AS attributed_by_link,
           count(*) FILTER (WHERE u IS NULL) AS remain_anonymous
    FROM ev WHERE user_id IS NULL
),

-- ---- MET-01 signup conversion on the visitor unit ------------------------------------------------------------------------
sc_visitors AS (
    SELECT DISTINCT anonymous_id FROM ev, w WHERE name = 'visit' AND anonymous_id IS NOT NULL AND at >= w.sc_from AND at < w.sc_to
),
sc_signed AS (
    SELECT DISTINCT anonymous_id FROM ev, w
    WHERE name = 'signup' AND anonymous_id IN (SELECT anonymous_id FROM sc_visitors) AND at >= w.sc_from AND at < w.sc_to
),

-- ---- MET-03 funnel: strict order, gap inclusive, window on the first step, no re-anchoring --------------------------------
chain AS (
    SELECT ev.vk, 1 AS k, min(ev.at) AS at
    FROM ev, fd WHERE ev.name = fd.steps[1] AND ev.at >= fd.window_from AND ev.at < fd.window_to GROUP BY ev.vk
  UNION ALL
    SELECT c.vk, c.k + 1,
           (SELECT min(e2.at) FROM ev e2 WHERE e2.vk = c.vk AND e2.name = fd.steps[c.k + 1]
              AND e2.at > c.at AND e2.at <= c.at + make_interval(hours => fd.max_gap_hours))
    FROM chain c, fd WHERE c.k < cardinality(fd.steps) AND c.at IS NOT NULL
),
fsteps AS (
    SELECT s.ord, s.name, (SELECT count(*) FROM chain c WHERE c.k = s.ord AND c.at IS NOT NULL) AS units
    FROM fd, unnest(fd.steps) WITH ORDINALITY AS s (name, ord)
),

-- ---- accounts: signup (earliest signup of a non-bot user), activation, sessions ----------------------------------------
signup AS (SELECT acct, min(at) AS at FROM ev WHERE name = 'signup' AND acct IS NOT NULL GROUP BY acct),
sess AS (
    SELECT s.user_id, u.account_id AS acct, s.started_at AS at FROM sessions s
    JOIN users u ON u.user_id = s.user_id JOIN accounts a ON a.account_id = u.account_id, p
    WHERE NOT u.bot_flag AND NOT a.internal AND s.started_at < p.cutoff
),

-- ---- MET-02 activation ---------------------------------------------------------------------------------------------------
ac_pop AS (
    SELECT s.acct, s.at, (s.at + make_interval(days => w.ac_days) <= p.cutoff) AS mature,
           EXISTS (SELECT 1 FROM ev WHERE ev.acct = s.acct AND ev.name = 'activated' AND ev.at >= s.at
                   AND ev.at < s.at + make_interval(days => w.ac_days)) AS activated
    FROM signup s, w, p WHERE s.at >= w.ac_from AND s.at < w.ac_to
),

-- ---- MET-04/05 retention on the account's calendar -----------------------------------------------------------------------
rt AS (
    SELECT s.acct, a.timezone AS tz, (s.at AT TIME ZONE a.timezone)::date AS d0,
           (p.cutoff AT TIME ZONE a.timezone)::date AS dc
    FROM signup s JOIN accounts a ON a.account_id = s.acct, w, p
    WHERE (s.at AT TIME ZONE a.timezone)::date >= w.rt_from AND (s.at AT TIME ZONE a.timezone)::date < w.rt_to
),
rt_flags AS (
    SELECT rt.*, (d0 + 8 <= dc) AS m7, (d0 + 35 <= dc) AS m35,
           EXISTS (SELECT 1 FROM sess WHERE sess.acct = rt.acct AND (sess.at AT TIME ZONE rt.tz)::date - rt.d0 = 7) AS on7,
           EXISTS (SELECT 1 FROM sess WHERE sess.acct = rt.acct AND (sess.at AT TIME ZONE rt.tz)::date - rt.d0 >= 7) AS after7,
           EXISTS (SELECT 1 FROM sess WHERE sess.acct = rt.acct AND (sess.at AT TIME ZONE rt.tz)::date - rt.d0 BETWEEN 28 AND 34) AS w4
    FROM rt
),
rt_internal AS (
    SELECT count(DISTINCT c.acct) AS n FROM classified c JOIN accounts a ON a.account_id = c.acct, w
    WHERE c.cls = 'internal' AND c.event_name = 'signup'
      AND (c.event_at AT TIME ZONE a.timezone)::date >= w.rt_from AND (c.event_at AT TIME ZONE a.timezone)::date < w.rt_to
),

-- ---- MET-06 feature adoption -----------------------------------------------------------------------------------------------
fa_active AS (
    SELECT DISTINCT sess.acct FROM sess, w WHERE sess.at >= w.fa_from AND sess.at < w.fa_to
),
fa_elig AS (
    SELECT a.account_id AS acct FROM fa_active f JOIN accounts a ON a.account_id = f.acct, w WHERE w.fa_plans ? a.plan
),
fa_uses AS (
    SELECT ev.acct FROM ev, w WHERE ev.name = 'feature_used' AND ev.acct IN (SELECT acct FROM fa_elig)
      AND ev.at >= w.fa_from AND ev.at < w.fa_to AND ev.props ->> 'feature' = w.fa_feature
),

-- ---- the experiment (D-03) --------------------------------------------------------------------------------------------------
vs AS (SELECT k AS v, (pl.alloc ->> k)::numeric AS share FROM pl, jsonb_object_keys(pl.alloc) AS k),
asg AS (
    SELECT a.assignment_id, a.unit_id, a.variant, a.assigned_at, sg.at AS signup_at,
           (sg.at IS NOT NULL AND sg.at + make_interval(days => pl.win) <= p.cutoff) AS mature,
           (sg.at IS NOT NULL AND EXISTS (SELECT 1 FROM ev WHERE ev.acct = a.unit_id AND ev.name = 'activated' AND ev.at >= sg.at
                                           AND ev.at < sg.at + make_interval(days => pl.win))) AS activated,
           EXISTS (SELECT 1 FROM exposures x WHERE x.assignment_id = a.assignment_id AND x.exposed_at <= p.cutoff) AS exposed,
           EXISTS (SELECT 1 FROM ev WHERE ev.acct = a.unit_id AND ev.name = 'product_error' AND ev.at >= a.assigned_at
                   AND ev.at < a.assigned_at + make_interval(days => pl.g_days)) AS errored,
           coalesce((SELECT sum(s.amount_usd) FROM subscriptions s WHERE s.account_id = a.unit_id AND s.status IN ('active', 'ended')
                     AND s.starts_at >= pl.rev_from AND s.starts_at < pl.rev_to AND s.starts_at <= p.cutoff), 0) AS revenue
    FROM assignments a JOIN pl ON a.experiment_version_id = pl.xv LEFT JOIN signup sg ON sg.acct = a.unit_id, p
    WHERE a.assigned_at <= p.cutoff   -- D-08: the cutoff rule
),
cnt AS (
    SELECT vs.v, vs.share,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v) AS assigned,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v AND asg.mature) AS n,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v AND asg.mature AND asg.activated) AS act,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v AND asg.mature AND asg.exposed) AS exposed,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v AND asg.mature AND asg.exposed AND asg.activated) AS exp_act,
           (SELECT count(*) FROM asg WHERE asg.variant = vs.v AND asg.mature AND asg.errored) AS errs,
           (SELECT coalesce(sum(asg.revenue), 0) FROM asg WHERE asg.variant = vs.v AND asg.mature) AS rev_total
    FROM vs
),
tot AS (SELECT coalesce(sum(assigned), 0) AS n_assigned, coalesce(sum(n), 0) AS n_mature FROM cnt),

-- sample ratio: chi-square, p = erfc(sqrt(stat / 2)) by the series of erf in NUMERIC
chi AS (
    SELECT tot.n_assigned,
           (SELECT sum((cnt.assigned - tot.n_assigned * cnt.share) ^ 2 / nullif(tot.n_assigned * cnt.share, 0)) FROM cnt) AS stat,
           (SELECT min(tot.n_assigned * cnt.share) FROM cnt) AS min_expected
    FROM tot
),
erf_in AS (
    SELECT stat, CASE WHEN stat > 0 AND stat <= 100 THEN sqrt(round(stat / 2, 90)) END AS x FROM chi WHERE n_assigned > 0
),
erf_series (n, term, s, x) AS (
    SELECT 0, round(x, 90), 0::numeric, round(x, 90) FROM erf_in WHERE x IS NOT NULL
  UNION ALL
    SELECT n + 1, round(-term * x * x / (n + 1), 90), s + round(term / (2 * n + 1), 90), x FROM erf_series WHERE abs(term) > 1e-70
),
pval AS (
    SELECT chi.n_assigned,
           CASE WHEN chi.n_assigned = 0 THEN NULL
                WHEN chi.stat <= 0 THEN 1::numeric
                WHEN chi.stat > 100 THEN 0::numeric
                ELSE 1 - 2 * (SELECT s FROM erf_series ORDER BY n DESC LIMIT 1)
                          / sqrt(3.14159265358979323846264338327950288419716939937510582097494459230781640628620899862803482534211706798::numeric(110,100))
           END AS p
    FROM chi
),

-- Wilson and Newcombe per variant (z from the plan; square roots at 40 decimals)
wil AS (
    SELECT c.v, c.n, c.act,
           CASE WHEN c.n > 0 THEN c.act::numeric / c.n END AS pr,
           CASE WHEN c.n > 0 THEN (c.act::numeric / c.n + pl.z ^ 2 / (2 * c.n)
                    - pl.z * sqrt(round((c.act::numeric / c.n) * (1 - c.act::numeric / c.n) / c.n + pl.z ^ 2 / (4 * c.n::numeric * c.n), 40)))
                    / (1 + pl.z ^ 2 / c.n) END AS lo,
           CASE WHEN c.n > 0 THEN (c.act::numeric / c.n + pl.z ^ 2 / (2 * c.n)
                    + pl.z * sqrt(round((c.act::numeric / c.n) * (1 - c.act::numeric / c.n) / c.n + pl.z ^ 2 / (4 * c.n::numeric * c.n), 40)))
                    / (1 + pl.z ^ 2 / c.n) END AS hi
    FROM cnt c, pl
),
nc AS (
    SELECT t.pr - c.pr AS d,
           (t.pr - c.pr) - sqrt(round((t.pr - t.lo) ^ 2 + (c.hi - c.pr) ^ 2, 40)) AS lo,
           (t.pr - c.pr) + sqrt(round((t.hi - t.pr) ^ 2 + (c.pr - c.lo) ^ 2, 40)) AS hi,
           c.pr AS control_pr
    FROM wil t, wil c WHERE t.v = 'treatment' AND c.v = 'control' AND t.n > 0 AND c.n > 0
),

-- revenue: mean, variance, standard error and interval bounds in SQL; the t quantile of df = n - 1 from the Python table
rev AS (
    SELECT c.v, c.n AS units, c.rev_total AS total,
           CASE WHEN c.n > 0 THEN round(c.rev_total / c.n, 2) END AS mean2,
           CASE WHEN c.n > 1 THEN
                (SELECT sum((a.revenue - round(c.rev_total / c.n, 40)) ^ 2) FROM asg a WHERE a.variant = c.v AND a.mature) / (c.n - 1) END AS var,
           t.t AS tq
    FROM cnt c LEFT JOIN t_critical_975 t ON t.df = c.n - 1 AND (SELECT confidence FROM pl) = '0.95'
),
rev2 AS (
    SELECT rev.*, CASE WHEN units > 1 AND tq IS NOT NULL THEN tq * sqrt(round(var / units, 40)) END AS half FROM rev
),

-- the run under test
run AS (
    SELECT r.* FROM analysis_runs r, pl, p
    WHERE r.experiment_version_id = pl.xv AND CASE WHEN %(run_id)s::text IS NOT NULL THEN r.analysis_id = %(run_id)s::text
                                                    ELSE r.cutoff_at = p.cutoff END
    ORDER BY r.created_at, r.analysis_id LIMIT 1
),
runs_of AS (SELECT r.* FROM analysis_runs r, pl WHERE r.experiment_version_id = pl.xv),
obs AS (
    SELECT o.*, a.signup_at, a.activated, a.assignment_id AS aid
    FROM metric_observations o JOIN asg a ON a.assignment_id = o.assignment_id, p WHERE o.window_end <= p.cutoff   -- D-08
),

-- ---- the experiment block ----------------------------------------------------------------------------------------------------
exp AS (
    SELECT pl.xv, pl.unit_type, pl.alloc, pl.config_hash, pl.hash_ok, pl.planned_end, p.cutoff,
           (p.cutoff < pl.planned_end) AS interim,
           (SELECT count(*) FROM runs_of) > 0 AND pl.frozen_at <= (SELECT min(created_at) FROM runs_of) AS plan_frozen,
           (SELECT analysis_id FROM run) AS run_id, (SELECT count(*) FROM runs_of ro WHERE ro.created_at < (SELECT created_at FROM run)) AS prior_n,
           (SELECT config_hash FROM run) AS run_hash
    FROM pl, p
),
srm_json AS (
    SELECT CASE WHEN tot.n_assigned = 0 THEN
               jsonb_build_object('observed', (SELECT jsonb_object_agg(v, assigned) FROM cnt), 'expected', NULL, 'statistic', NULL,
                                  'p_value', NULL, 'verdict', 'INSUFFICIENT')
           ELSE jsonb_build_object(
               'observed', (SELECT jsonb_object_agg(v, assigned) FROM cnt),
               'expected', (SELECT jsonb_object_agg(v, round(tot.n_assigned * share, 2)::text) FROM cnt),
               'statistic', round(chi.stat, 6)::text, 'p_value', round(pval.p, 6)::text,
               'df', (SELECT count(*) - 1 FROM cnt),
               'verdict', CASE WHEN chi.min_expected < pl.min_cell THEN 'INSUFFICIENT' WHEN pval.p < pl.p_threshold THEN 'MISMATCH' ELSE 'OK' END)
           END AS j
    FROM tot, chi, pval, pl
)
SELECT
    (SELECT jsonb_build_object('window', jsonb_build_object('from', to_char(w.sc_from AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                                              'to', to_char(w.sc_to AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
                               'unit', 'distinct anonymous_id', 'visitors', (SELECT count(*) FROM sc_visitors),
                               'signed_up', (SELECT count(*) FROM sc_signed),
                               'rate', CASE WHEN (SELECT count(*) FROM sc_visitors) > 0
                                            THEN round((SELECT count(*) FROM sc_signed)::numeric / (SELECT count(*) FROM sc_visitors), 6)::text END)
     FROM w) AS signup_conversion,

    (SELECT jsonb_build_object('definition_id', fd.definition_id, 'version', fd.version, 'max_gap_hours', fd.max_gap_hours,
                               'window', jsonb_build_object('from', to_char(fd.window_from AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                                              'to', to_char(fd.window_to AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
                               'steps', (SELECT jsonb_agg(jsonb_build_object(
                                    'step', s.name, 'units', s.units,
                                    'conversion_from_previous', CASE WHEN s.ord = 1 THEN NULL
                                         WHEN prev.units > 0 THEN round(s.units::numeric / prev.units, 6)::text END,
                                    'conversion_from_first', CASE WHEN f1x.units > 0 THEN round(s.units::numeric / f1x.units, 6)::text END)
                                    ORDER BY s.ord)
                                 FROM fsteps s LEFT JOIN fsteps prev ON prev.ord = s.ord - 1, (SELECT units FROM fsteps WHERE ord = 1) f1x),
                               'overall_conversion', (SELECT CASE WHEN f1.units > 0 THEN round(fl.units::numeric / f1.units, 6)::text END
                                                      FROM (SELECT units FROM fsteps WHERE ord = 1) f1,
                                                           (SELECT units FROM fsteps ORDER BY ord DESC LIMIT 1) fl))
     FROM fd) AS funnel,

    (SELECT jsonb_build_object('window', jsonb_build_object('from', to_char(w.ac_from AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                                              'to', to_char(w.ac_to AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
                               'window_days', w.ac_days, 'signups', (SELECT count(*) FROM ac_pop),
                               'immature_excluded', (SELECT count(*) FROM ac_pop WHERE NOT mature),
                               'mature_accounts', (SELECT count(*) FROM ac_pop WHERE mature),
                               'activated', (SELECT count(*) FROM ac_pop WHERE mature AND activated),
                               'rate', CASE WHEN (SELECT count(*) FROM ac_pop WHERE mature) > 0
                                            THEN round((SELECT count(*) FROM ac_pop WHERE mature AND activated)::numeric
                                                       / (SELECT count(*) FROM ac_pop WHERE mature), 6)::text END)
     FROM w) AS activation,

    (SELECT jsonb_build_object(
        'signup_window', jsonb_build_object('from', w.rt_from::text, 'to', w.rt_to::text), 'calendar', 'account timezone',
        'cohort_accounts', (SELECT count(*) FROM rt), 'excluded_internal_accounts', (SELECT n FROM rt_internal),
        'day7', jsonb_build_object('mature_accounts', (SELECT count(*) FROM rt_flags WHERE m7),
                                   'immature_excluded', (SELECT count(*) FROM rt_flags WHERE NOT m7),
                                   'retained', (SELECT count(*) FROM rt_flags WHERE m7 AND on7),
                                   'rate', CASE WHEN (SELECT count(*) FROM rt_flags WHERE m7) > 0
                                                THEN round((SELECT count(*) FROM rt_flags WHERE m7 AND on7)::numeric
                                                           / (SELECT count(*) FROM rt_flags WHERE m7), 6)::text END),
        'on_or_after_day7', jsonb_build_object('mature_accounts', (SELECT count(*) FROM rt_flags WHERE m7),
                                   'retained', (SELECT count(*) FROM rt_flags WHERE m7 AND after7),
                                   'rate', CASE WHEN (SELECT count(*) FROM rt_flags WHERE m7) > 0
                                                THEN round((SELECT count(*) FROM rt_flags WHERE m7 AND after7)::numeric
                                                           / (SELECT count(*) FROM rt_flags WHERE m7), 6)::text END),
        'week4', jsonb_build_object('mature_accounts', (SELECT count(*) FROM rt_flags WHERE m35),
                                    'immature_excluded', (SELECT count(*) FROM rt_flags WHERE NOT m35),
                                    'retained', (SELECT count(*) FROM rt_flags WHERE m35 AND w4),
                                    'rate', CASE WHEN (SELECT count(*) FROM rt_flags WHERE m35) > 0
                                                 THEN round((SELECT count(*) FROM rt_flags WHERE m35 AND w4)::numeric
                                                            / (SELECT count(*) FROM rt_flags WHERE m35), 6)::text END))
     FROM w) AS retention,

    (SELECT jsonb_build_object('window', jsonb_build_object('from', to_char(w.fa_from AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                                              'to', to_char(w.fa_to AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
                               'feature', w.fa_feature, 'eligible_plans', w.fa_plans, 'eligible_accounts', (SELECT count(*) FROM fa_elig),
                               'adopting_accounts', (SELECT count(DISTINCT acct) FROM fa_uses), 'use_events', (SELECT count(*) FROM fa_uses),
                               'rate', CASE WHEN (SELECT count(*) FROM fa_elig) > 0
                                            THEN round((SELECT count(DISTINCT acct) FROM fa_uses)::numeric / (SELECT count(*) FROM fa_elig), 6)::text END)
     FROM w) AS feature_adoption,

    (SELECT jsonb_build_object(
        'experiment_version_id', exp.xv, 'unit_type', exp.unit_type, 'allocation', exp.alloc,
        'run', jsonb_build_object('analysis_id', exp.run_id, 'cutoff_at', to_char(exp.cutoff AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                  'planned_end', to_char(exp.planned_end AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                  'interim', exp.interim, 'prior_runs', CASE WHEN exp.run_id IS NULL THEN NULL ELSE exp.prior_n END,
                                  'plan_frozen', exp.plan_frozen, 'config_hash', exp.config_hash,
                                  'config_hash_matches_plan', exp.hash_ok AND exp.run_id IS NOT NULL AND exp.run_hash = exp.config_hash),
        'assigned_units', tot.n_assigned, 'mature_units', tot.n_mature, 'immature_or_unobserved_excluded', tot.n_assigned - tot.n_mature,
        'srm', srm_json.j,
        'primary', jsonb_build_object(
            'metric', pl.primary_metric, 'analysis', 'intention_to_treat',
            'variants', (SELECT jsonb_object_agg(c.v, jsonb_build_object(
                    'assigned', c.assigned, 'mature_units', c.n, 'activated', c.act,
                    'conversion', CASE WHEN c.n > 0 THEN round(wil.pr, 6)::text END,
                    'wilson_95', CASE WHEN c.n > 0 THEN jsonb_build_object('low', round(wil.lo, 6)::text, 'high', round(wil.hi, 6)::text) END))
                 FROM cnt c JOIN wil ON wil.v = c.v),
            'absolute_lift_pp', (SELECT round(nc.d * 100, 2)::text FROM nc),
            'relative_lift', (SELECT CASE WHEN nc.control_pr > 0 THEN round(nc.d / nc.control_pr, 6)::text END FROM nc),
            'interval', (SELECT jsonb_build_object('method', 'newcombe_hybrid_score', 'confidence', pl.confidence, 'z', pl.z_text,
                                                   'low', round(nc.lo, 6)::text, 'high', round(nc.hi, 6)::text,
                                                   'low_pp', round(nc.lo * 100, 2)::text, 'high_pp', round(nc.hi * 100, 2)::text,
                                                   'includes_zero', (nc.lo <= 0 AND nc.hi >= 0)) FROM nc),
            'conclusive', coalesce((SELECT NOT (nc.lo <= 0 AND nc.hi >= 0) AND NOT exp.interim AND exp.hash_ok FROM nc), false)),
        'exposure', jsonb_build_object('definition', 'exposed mature assigned accounts / mature assigned accounts',
            'by_variant', (SELECT jsonb_object_agg(c.v, jsonb_build_object('exposed', c.exposed, 'units', c.n,
                              'rate', CASE WHEN c.n > 0 THEN round(c.exposed::numeric / c.n, 6)::text END)) FROM cnt c),
            'overall', jsonb_build_object('exposed', (SELECT sum(exposed) FROM cnt), 'units', tot.n_mature,
                              'rate', CASE WHEN tot.n_mature > 0 THEN round((SELECT sum(exposed) FROM cnt)::numeric / tot.n_mature, 6)::text END)),
        'exploratory_exposed_only', jsonb_build_object('label', 'exploratory', 'decision_basis', false,
            'by_variant', (SELECT jsonb_object_agg(c.v, jsonb_build_object('exposed_units', c.exposed, 'activated', c.exp_act,
                              'conversion', CASE WHEN c.exposed > 0 THEN round(c.exp_act::numeric / c.exposed, 6)::text END)) FROM cnt c)),
        'guardrail', jsonb_build_object('metric', pl.g_metric, 'window_days', pl.g_days,
            'by_variant', (SELECT jsonb_object_agg(c.v, jsonb_build_object('eligible_units', c.n, 'units_with_error', c.errs,
                              'error_rate', CASE WHEN c.n > 0 THEN round(c.errs::numeric / c.n, 6)::text END)) FROM cnt c)),
        'revenue_per_assigned_account', jsonb_build_object('currency', 'USD',
            'window', jsonb_build_object('from', to_char(pl.rev_from AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
                                         'to', to_char(pl.rev_to AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
            'by_variant', (SELECT jsonb_object_agg(r.v, jsonb_build_object('units', r.units, 'total', round(r.total, 2)::text,
                              'mean', r.mean2::text,
                              'interval', CASE WHEN r.half IS NOT NULL THEN jsonb_build_object('df', r.units - 1, 't', round(r.tq, 6)::text,
                                   'low', round(r.total / r.units - r.half, 2)::text, 'high', round(r.total / r.units + r.half, 2)::text) END))
                           FROM rev2 r)),
        'observations', jsonb_build_object('rows_accepted', (SELECT count(*) FROM obs),
            'rows_matching_events', (SELECT count(*) FROM obs WHERE signup_at IS NOT NULL
                 AND obs.value = CASE WHEN activated THEN '1' ELSE '0' END AND obs.window_end = signup_at + make_interval(days => pl.win))))
     FROM exp, tot, srm_json, pl) AS experiment,

