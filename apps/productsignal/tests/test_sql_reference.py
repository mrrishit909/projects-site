"""data/sql/reference_metrics.sql recomputes every metric from the facts, independently of the Python domain and of any stored
status or result, and equals expected.json on the fixtures and the domain on any loaded population.

The chi-square p-value is a SQL series; the Student t quantile is read from t_critical_975 (a table generated by Python at 20
decimals: the one number SQL cannot reproduce), everything around it is SQL."""
from decimal import Decimal
from pathlib import Path

import psycopg
import pytest

from productsignal import run_pipeline
from productsignal.contract import METRIC_KEYS
from productsignal.stats import t_crit
from productsignal.timeutil import parse_ts

from support_db import World, conn, db_url, flat, golden_expected, golden_inputs, iso, load, random_world, small_experiment, ts  # noqa: F401
from datetime import timedelta

SQL = (Path(__file__).resolve().parents[1] / "data" / "sql" / "reference_metrics.sql").read_text()
COLUMNS = (*METRIC_KEYS, "tracking_quality", "identity", "empty_population")


def reference(conn, cutoff, xv=None, run_id=None):
    return conn.execute(SQL, {"cutoff": parse_ts(cutoff), "xv": xv, "run_id": run_id}).fetchone()


def assert_equals_domain(row, res):
    for k in METRIC_KEYS:
        assert row[k] == res.metrics[k], k
    assert row["tracking_quality"] == res.tracking_quality and row["identity"] == res.identity
    assert row["empty_population"] == res.empty_population


@pytest.mark.parametrize("variant", ["", "variant-rejected", "variant-empty"])
def test_sql_equals_expected_for_every_fixture(conn, variant):
    inputs = golden_inputs(variant)
    load(conn, inputs)
    row = reference(conn, inputs["cutoff"])
    want = golden_expected(variant)
    assert set(row) == set(COLUMNS)
    for k in METRIC_KEYS:
        assert row[k] == want["metrics"][k], k
    assert row["tracking_quality"] == want["tracking_quality"] and row["identity"] == want["identity"]
    assert row["empty_population"] is want["empty_population"]
    leaves = {k: v for k, v in flat({k: row[k] for k in METRIC_KEYS}).items()}
    assert leaves == flat(want["metrics"])                                          # every leaf, key by key


def test_sql_is_independent_of_every_stored_status_result_and_derived_column(conn):
    """Scramble what the commands store (run results, verdicts, reviews, decisions, audit, command results): the SQL does not read them."""
    inputs = golden_inputs()
    load(conn, inputs)
    want = golden_expected()
    with conn.transaction():
        for t in ("analysis_runs", "analysis_plans", "audit_events"):
            conn.execute(f"ALTER TABLE {t} DISABLE TRIGGER USER")                    # constants
        conn.execute("UPDATE analysis_runs SET interim = NOT false, srm_verdict = 'MISMATCH', conclusive = true, prior_runs = 99, "
                     "result = '{\"srm\": {\"verdict\": \"MISMATCH\"}}', created_by = 'x'")
        conn.execute("UPDATE analysis_plans SET frozen_at = now(), frozen_by = 'x'")      # the plan's own frozen_at lives in plan jsonb
        for t in ("analysis_runs", "analysis_plans", "audit_events"):
            conn.execute(f"ALTER TABLE {t} ENABLE TRIGGER USER")
    conn.execute("INSERT INTO audit_events (event_id, entity_type, entity_id, action, actor_id) VALUES ('e', 't', 'i', 'a', 'x')")
    conn.execute("INSERT INTO command_results VALUES ('k', 'h', 'a', 'admin', 'c', 's', '{}')")
    row = reference(conn, inputs["cutoff"])
    for k in METRIC_KEYS:
        assert row[k] == want["metrics"][k], k


def test_sql_is_independent_of_the_session_time_zone(conn):
    inputs = golden_inputs()
    load(conn, inputs)
    base = reference(conn, inputs["cutoff"])
    for tz in ("Pacific/Kiritimati", "America/Los_Angeles"):
        conn.execute(f"SET TIME ZONE '{tz}'")                                         # constants
        assert reference(conn, inputs["cutoff"]) == base, tz


def test_sql_spec_sentence_values(conn):
    inputs = golden_inputs()
    load(conn, inputs)
    e = reference(conn, inputs["cutoff"])["experiment"]
    assert (e["primary"]["variants"]["control"]["conversion"], e["primary"]["variants"]["treatment"]["conversion"]) == ("0.200000", "0.300000")
    assert (e["primary"]["absolute_lift_pp"], e["primary"]["relative_lift"], e["primary"]["conclusive"]) == ("10.00", "0.500000", False)
    assert (e["primary"]["interval"]["low"], e["primary"]["interval"]["high"]) == ("-0.020249", "0.216734")
    assert e["srm"] == {"observed": {"control": 100, "treatment": 100}, "expected": {"control": "100.00", "treatment": "100.00"},
                        "statistic": "0.000000", "p_value": "1.000000", "df": 1, "verdict": "OK"}
    assert reference(conn, inputs["cutoff"])["retention"]["day7"]["rate"] == "0.250000"


def rich_world() -> dict:
    """Every rule at once, loaded with a plan that has runs: a 130/70 sample ratio mismatch with the p-value as a series, intervals,
    revenue in every status, late and duplicate events, links, timezones and three runs."""
    w = World()
    c = w.arm("control", 130, 20)
    t = w.arm("treatment", 70, 28, start="2026-10-01T14:00:00Z")
    w.sub(c[3], "2026-10-03T00:00:00Z", "49.00")
    w.sub(c[4], "2026-10-04T00:00:00Z", "10.50", status="ended")
    w.sub(c[5], "2026-10-04T00:00:00Z", "99.00", status="refunded")
    for i, a in enumerate(t[:7]):
        w.sub(a, "2026-10-0%dT00:00:00Z" % (2 + i % 5), "%d.25" % (10 * (i + 1)))
    w.event("product_error", "2026-10-02T09:00:00Z", user=f"u-{c[0]}")
    w.event("product_error", "2026-10-05T09:00:00Z", user=f"u-{t[0]}")
    w.activate(c[40], "2026-10-02T00:00:00Z", recv="2026-10-20T00:00:00Z")
    w.event("feature_used", "2026-09-22T11:00:00Z", user=f"u-{c[0]}", props={"feature": "export"}, eid="ev-f1")
    w.event("feature_used", "2026-09-22T11:00:00Z", user=f"u-{c[0]}", props={"feature": "export"}, eid="ev-f1b", recv="2026-09-22T11:00:09Z")
    w.session(c[0], "2026-09-22T10:00:00Z")
    w.link("a-1", f"u-{c[1]}", "2026-10-06T10:00:00Z")
    w.event("visit", "2026-10-06T09:00:00Z", anon="a-1")
    w.event("visit", "2026-10-06T10:00:00Z", anon="a-1")
    w.event("signup", "2026-10-06T10:30:00Z", anon="a-1")
    w.event("visit", "2026-10-06T08:00:00Z", user="u-ghost")
    w.run("2026-10-10T00:00:00Z", "2026-10-10T01:00:00Z")
    w.run("2026-10-20T00:00:00Z", "2026-10-20T01:00:00Z")
    w.run("2026-10-26T00:00:00Z", "2026-10-26T01:00:00Z")
    return w.data()


@pytest.mark.parametrize("cutoff", ["2026-10-26T00:00:00Z", "2026-10-19T00:00:00Z", "2026-10-10T00:00:00Z", "2026-10-02T00:00:00Z"])
def test_sql_equals_the_domain_on_a_rich_population(conn, cutoff):
    d = rich_world()
    d["cutoff"] = cutoff
    res = run_pipeline(d)
    load(conn, d)
    assert_equals_domain(reference(conn, cutoff), res)
    if cutoff == "2026-10-26T00:00:00Z":                                               # the world really exercises the rules
        e = res.metrics["experiment"]
        assert e["srm"]["verdict"] == "MISMATCH" and e["srm"]["p_value"] == "0.000022"
        assert e["revenue_per_assigned_account"]["by_variant"]["treatment"]["interval"] is not None
        assert e["run"]["prior_runs"] == 2 and e["primary"]["interval"] is not None


def test_sql_run_and_experiment_parameters(conn):
    d = rich_world()
    load(conn, d)
    for rid in ("an-001", "an-002", "an-003"):
        assert reference(conn, d["cutoff"], run_id=rid)["experiment"]["run"] == run_pipeline(d, run_id=rid).metrics["experiment"]["run"], rid
    assert reference(conn, d["cutoff"], xv="xv-001")["experiment"]["experiment_version_id"] == "xv-001"
    assert reference(conn, d["cutoff"], xv="xv-none")["experiment"] is None
    assert run_pipeline(d, experiment_version_id="xv-none").metrics["experiment"] is None


@pytest.mark.parametrize("start", range(0, 120, 20))
def test_sql_equals_the_domain_on_random_populations(conn, start):
    """Seeded random populations (timezones, bots, internal accounts, links, duplicates, late events, window edges, runs); each
    one is loaded in a transaction that is rolled back."""
    for s in range(start, start + 20):
        d = random_world(s)
        res = run_pipeline(d)
        with conn.transaction():                      # psycopg.Rollback ends the block and discards the load
            load_in_open(conn, d)
            row = reference(conn, d["cutoff"])
            diffs = [k for k in COLUMNS if row[k] != (getattr(res, k) if k in ("tracking_quality", "identity", "empty_population") else res.metrics[k])]
            assert not diffs, (s, diffs)
            raise psycopg.Rollback()


def load_in_open(conn, d):
    """seed.seed inside the caller's transaction."""
    from data import seed
    seed.seed(conn, d)


def test_sql_big_arms_use_the_t_quantile_table_and_the_domain_agrees(conn):
    w = small_experiment((300, 90), (300, 130))
    for i in range(0, 300, 7):
        w.sub(f"acc-c-{i + 1:03d}", "2026-10-03T00:00:00Z", "%d.99" % (1 + i % 40))
        w.sub(f"acc-t-{i + 1:03d}", "2026-10-04T00:00:00Z", "%d.50" % (5 + i % 60))
    d = w.data()
    res = run_pipeline(d)
    load(conn, d)
    row = reference(conn, d["cutoff"])
    assert row["experiment"]["revenue_per_assigned_account"] == res.metrics["experiment"]["revenue_per_assigned_account"]
    assert row["experiment"]["revenue_per_assigned_account"]["by_variant"]["control"]["interval"]["df"] == 299
    assert row["experiment"]["primary"] == res.metrics["experiment"]["primary"]


@pytest.mark.parametrize("df", [1, 2, 3, 10, 17, 50, 99, 120, 401, 999])
def test_the_python_generated_t_table_equals_the_exact_quantile(conn, df):
    load(conn, golden_inputs("variant-empty"))
    got = conn.execute("SELECT t FROM t_critical_975 WHERE df = %s", (df,)).fetchone()["t"]
    assert got == t_crit(df).quantize(Decimal("1e-20"))


def test_sql_without_a_t_table_row_has_no_interval_rather_than_a_wrong_one(conn):
    d = golden_inputs()
    load(conn, d)
    conn.execute("DELETE FROM t_critical_975 WHERE df = 99")
    by = reference(conn, d["cutoff"])["experiment"]["revenue_per_assigned_account"]["by_variant"]
    assert by["control"]["interval"] is None and by["control"]["mean"] == "1.48"
